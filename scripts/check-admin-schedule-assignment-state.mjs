check('legacy member counts are removed from display and auto-name detection', () => {
  assert.equal(stripDynamicMemberCount('พื้นฐาน / เริ่มต้น (2 คน)'), 'พื้นฐาน / เริ่มต้น')
  assert.equal(isAutoGeneratedAssignmentGroupName('พื้นฐาน / เริ่มต้น (2 คน)'), true)
  const result = resolveAssignmentGroupName({
    currentName: 'พื้นฐาน / เริ่มต้น (2 คน)',
    students: [namingStudent(3), namingStudent(6), namingStudent(8)],
  })
  assert.equal(result.name, 'ชุดพื้นฐาน')
  assert.doesNotMatch(result.name, /\(\d+ คน\)$/u)
})

