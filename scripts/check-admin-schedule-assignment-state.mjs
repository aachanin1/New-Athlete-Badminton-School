const namingStudent = (level, levelCategory = 'basic', levelProgramName = 'ชุดพื้นฐาน') => ({
  level,
  levelCategory,
  levelProgramName,
})

check('exact group with an empty name derives its active level program name', () => {
  const result = resolveAssignmentGroupName({ currentName: '', students: [namingStudent(3), namingStudent(6)] })
  assert.deepEqual([result.name, result.autoNamed, result.error], ['ชุดพื้นฐาน', true, null])
})

check('exact group placeholder derives its active level program name', () => {
  const result = resolveAssignmentGroupName({ currentName: 'ยังไม่จัดกลุ่ม', students: [namingStudent(3)] })
  assert.equal(result.name, 'ชุดพื้นฐาน')
})

check('valid user-authored group name is preserved', () => {
  const result = resolveAssignmentGroupName({ currentName: 'ทีมวันพุธ', students: [namingStudent(3)] })
  assert.deepEqual([result.name, result.autoNamed], ['ทีมวันพุธ', false])
})

check('multiple actual levels in one confirmed category use the same source program name', () => {
  const result = deriveAssignmentGroupAutoName([namingStudent(1), namingStudent(20), namingStudent(34)])
  assert.deepEqual([result.name, result.levelMin, result.levelMax], ['ชุดพื้นฐาน', 1, 34])
})

check('mixed categories do not invent a new combined name', () => {
  const result = deriveAssignmentGroupAutoName([
    namingStudent(34),
    namingStudent(35, 'athlete_1', 'ชุดเตรียมนักกีฬา ชุด C'),
  ])
  assert.deepEqual([result.name, result.error], [null, 'mixed_level_categories'])
})

check('legacy member counts are removed from display and auto-name detection', () => {
  assert.equal(stripDynamicMemberCount('พื้นฐาน / เริ่มต้น (2 คน)'), 'พื้นฐาน / เริ่มต้น')
  assert.equal(isAutoGeneratedAssignmentGroupName('พื้นฐาน / เริ่มต้น (2 คน)'), true)
  const result = resolveAssignmentGroupName({
    currentName: 'พื้นฐาน / เริ่มต้น (2 คน)',
    students: [namingStudent(3), namingStudent(6), namingStudent(8)],
  })
  assert.equal(result.name, 'ชุดพื้นฐาน')
  assert.doesNotMatch(result.name, /\(\d+ คน\)$/u)
})

check('member counts are rendered dynamically from current arrays', () => {
  const assignmentClient = read('src/components/coach/assign-groups-client.tsx')
  assert.equal(assignmentClient.includes('{groupStudents.length} คน'), true)
  assert.equal(client.includes('ผู้เรียนในกลุ่มนี้ {group.learners.length} คน'), true)
  assert.equal(client.includes('stripDynamicMemberCount(group.name)'), true)
})

check('Coach Base LV 3 and LV 6 fixture deterministically proposes ชุดพื้นฐาน', () => {
  const result = resolveAssignmentGroupName({
    currentName: 'ยังไม่จัดกลุ่ม',
    students: [namingStudent(6), namingStudent(3)],
  })
  assert.deepEqual([result.name, result.levelMin, result.levelMax], ['ชุดพื้นฐาน', 3, 6])
})

check('normal save and retrospective coach replacement both enforce naming resolution', () => {
  assert.equal(assignmentRoute.includes('loadAssignmentGroupNamingStudents'), true)
  assert.equal(assignmentRoute.includes('resolveAssignmentGroupName'), true)
  assert.equal(makeupRoute.includes('loadAssignmentGroupNamingStudents'), true)
  assert.equal(makeupRoute.includes('resolveAssignmentGroupName'), true)
})

